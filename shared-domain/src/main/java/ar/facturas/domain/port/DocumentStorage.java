package ar.facturas.domain.port;

/**
 * Where the original files live.
 *
 * <p>The domain says <em>what</em> it needs from storage and nothing about
 * <em>how</em>. Today the adapter talks to S3Mock, tomorrow to S3 proper
 * or to MinIO; none of that reaches this interface. It is also what lets
 * Fase 2 move extraction into the worker without touching either side —
 * the worker gets the same port.
 *
 * <p>Files are capped at 10 MB by the upload endpoint, so {@code byte[]}
 * is fine and spares everyone the ceremony of streams. If that cap ever
 * rises, this is the signature to revisit.
 */
public interface DocumentStorage {

    /**
     * Stores the file and returns the key it was stored under.
     *
     * <p>The key is generated by the adapter, not by the caller: only the
     * adapter knows how its backend lays things out. It is opaque on
     * purpose — never the original filename, which the user controls and
     * which would leak into paths.
     *
     * @throws StorageException if the file could not be stored. Callers
     *         must treat this as fatal for the upload: a {@code Document}
     *         row pointing at a file that was never written is worse than
     *         a rejected upload.
     */
    String store(byte[] content, String contentType);

    /** @throws StorageException if the key does not exist or cannot be read. */
    byte[] retrieve(String storageKey);

    /** Silent when the key does not exist: deleting twice is not an error. */
    void delete(String storageKey);

    /**
     * Thrown for any storage failure. A single type on purpose — callers
     * react the same way to a timeout, a missing bucket or bad
     * credentials: reject the upload and keep the message useful.
     */
    class StorageException extends RuntimeException {
        public StorageException(String message, Throwable cause) {
            super(message, cause);
        }

        public StorageException(String message) {
            super(message);
        }
    }
}
